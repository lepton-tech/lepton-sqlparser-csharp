// Testes próprios do port (não existem no sqlparser-rs): fixam o consumo de tokens dos três pontos em que o
// Rust descarta o erro de um `expect_*` (convencoes.md §13, caso 81; docs/port/onda-d/D5.md):
//   - `UNNEST(..)`: `match self.expect_keywords(&[WITH, OFFSET]) { Ok(()) => true, Err(_) => false }`;
//   - `XMLTABLE(.. PASSING ..)`: `self.parse_keyword(BY) && self.expect_keyword(VALUE).is_ok()`;
//   - `GENERATED .. AS ..`: `if self.expect_token(&Token::LParen).is_ok() { .. }`.
// O `expect_keywords` chama `expect_keyword_is(kw)?` para cada keyword: consome as que casam e para na
// primeira que não casa, sem voltar a posição. Por isso um `WITH` sem `OFFSET` é consumido e some da
// consulta, e um `BY` sem `VALUE` também. O `expect_token(..)` só avança quando o token casa. Os
// resultados esperados abaixo foram derivados dessas regras do Rust (mod.rs 4859–4924, 9812, 9830,
// 9842, 16676–16679, 17072–17073).

using Lepton.SqlParser.Core.Ast;
using Lepton.SqlParser.Core.Dialects;

namespace Lepton.SqlParser.Core.Tests;

public class DiscardedExpectResultTests
{
    private static string RoundTrip(Dialect dialect, string sql)
    {
        var statements = Parser.ParseSql(dialect, sql);
        Assert.Single(statements);
        return statements[0].ToString();
    }

    [Fact]
    public void Unnest_com_WITH_OFFSET_completo()
    {
        // O `Display` do Rust escreve o alias do offset sem `AS` (query.rs, `TableFactor::UNNEST`).
        Assert.Equal(
            "SELECT * FROM UNNEST(a) AS t WITH OFFSET o",
            RoundTrip(new BigQueryDialect(), "SELECT * FROM UNNEST(a) AS t WITH OFFSET AS o"));
    }

    [Fact]
    public void Unnest_com_WITH_sem_OFFSET_consome_o_WITH()
    {
        // `expect_keywords` consome o `WITH` e falha no fim da entrada: `with_offset` é falso e o `WITH`
        // não volta. A instrução termina sem erro e o `WITH` desaparece.
        Assert.Equal(
            "SELECT * FROM UNNEST(a)",
            RoundTrip(new BigQueryDialect(), "SELECT * FROM UNNEST(a) WITH"));

        // Com outra palavra depois do `WITH`, o erro aponta para ela, não para o `WITH`.
        var ex = Assert.Throws<ParserException>(
            () => Parser.ParseSql(new BigQueryDialect(), "SELECT * FROM UNNEST(a) WITH x"));
        Assert.Equal(
            "sql parser error: Expected: end of statement, found: x at Line: 1, Column: 30",
            ex.Message);
    }

    [Fact]
    public void Unnest_sem_WITH_nao_consome_nada()
    {
        // Sem `WITH`, nada é consumido: o `ORDER BY` seguinte continua disponível.
        Assert.Equal(
            "SELECT * FROM UNNEST(a) ORDER BY 1",
            RoundTrip(new BigQueryDialect(), "SELECT * FROM UNNEST(a) ORDER BY 1"));
    }

    [Fact]
    public void Passing_com_BY_VALUE_completo()
    {
        Assert.Equal(
            "SELECT * FROM XMLTABLE('/root' PASSING BY VALUE data COLUMNS element TEXT)",
            RoundTrip(
                new GenericDialect(),
                "SELECT * FROM XMLTABLE('/root' PASSING BY VALUE data COLUMNS element TEXT)"));
    }

    [Fact]
    public void Passing_com_BY_sem_VALUE_consome_o_BY()
    {
        // `parse_keyword(BY)` consome o `BY`; `expect_keyword(VALUE)` falha sem consumir nada e o erro é
        // descartado. `by_value` é falso e a expressão é `data`.
        Assert.Equal(
            "SELECT * FROM XMLTABLE('/root' PASSING data COLUMNS element TEXT)",
            RoundTrip(
                new GenericDialect(),
                "SELECT * FROM XMLTABLE('/root' PASSING BY data COLUMNS element TEXT)"));
    }

    [Fact]
    public void Generated_identity_sem_parentese_nao_consome_o_token_seguinte()
    {
        // `expect_token(&Token::LParen)` falha sem consumir `NOT`, que vira a opção seguinte da coluna.
        Assert.Equal(
            "CREATE TABLE t (a INT GENERATED ALWAYS AS IDENTITY NOT NULL)",
            RoundTrip(
                new PostgreSqlDialect(),
                "CREATE TABLE t (a INT GENERATED ALWAYS AS IDENTITY NOT NULL)"));
        Assert.Equal(
            "CREATE TABLE t (a INT GENERATED BY DEFAULT AS IDENTITY NOT NULL)",
            RoundTrip(
                new PostgreSqlDialect(),
                "CREATE TABLE t (a INT GENERATED BY DEFAULT AS IDENTITY NOT NULL)"));
    }

    [Fact]
    public void Generated_identity_com_parentese()
    {
        Assert.Equal(
            "CREATE TABLE t (a INT GENERATED BY DEFAULT AS IDENTITY ( START WITH 1 ))",
            RoundTrip(
                new PostgreSqlDialect(),
                "CREATE TABLE t (a INT GENERATED BY DEFAULT AS IDENTITY (START WITH 1))"));
    }

    [Fact]
    public void Generated_always_as_sem_parentese_devolve_none_depois_de_consumir_ALWAYS_AS()
    {
        // Terceiro ramo: `parse_keywords(&[ALWAYS, AS])` consome as duas palavras; sem `(`, o
        // `expect_token` falha sem consumir e a função devolve `Ok(None)`. O erro seguinte aponta para `x`.
        var ex = Assert.Throws<ParserException>(
            () => Parser.ParseSql(new GenericDialect(), "CREATE TABLE t (a INT GENERATED ALWAYS AS x)"));
        Assert.Contains("found: x", ex.Message);
    }
}
