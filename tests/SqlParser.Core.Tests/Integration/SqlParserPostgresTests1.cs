    private static void TestOperator(string @operator, TestedDialects dialect, BinaryOperator expected)
    {
        var operatorTokens =
            new Tokenizer(new PostgreSqlDialect(), $"a{@operator}b")
                .Tokenize();
        // assert_eq!(operator_tokens.len(), 3, "binary op should be 3 tokens, not {operator_tokens:?}")
        Assert.True(
            operatorTokens.Count == 3,
            $"binary op should be 3 tokens, not [{string.Join(", ", operatorTokens.Select(t => t.ToDebugString()))}]");
        var expectedExpr = new Expr.BinaryOp(
            Left: new Expr.Identifier(new Ident("a")),
            Op: expected,
            Right: new Expr.Identifier(new Ident("b")));
        var strExprCanonical = $"a {@operator} b";
        Assert.Equal<Expr>(expectedExpr, dialect.VerifiedExpr(strExprCanonical));
        Assert.Equal<Expr>(
            expectedExpr,
            dialect.ExprParsesTo($"a{@operator}b", strExprCanonical));
    }

