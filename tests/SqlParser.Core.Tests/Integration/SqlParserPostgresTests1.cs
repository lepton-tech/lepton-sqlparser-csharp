    [Fact]
    public void parse_array_subscript()
    {
        var tests = new (string, Subscript)[]
        {
            (
                "(ARRAY[1, 2, 3, 4, 5, 6])[2]",
                new Subscript.Index(
                    IndexValue: Expr.MakeValue(TestUtils.Number("2")))
            ),
            (
                "(ARRAY[1, 2, 3, 4, 5, 6])[foo]",
                new Subscript.Index(
                    IndexValue: new Expr.Identifier(new Ident("foo")))
            ),
            (
                "(ARRAY[1, 2, 3, 4, 5, 6])[2:5]",
                new Subscript.Slice(
                    LowerBound: Expr.MakeValue(TestUtils.Number("2")),
                    UpperBound: Expr.MakeValue(TestUtils.Number("5")),
                    Stride: null)
            ),
            (
                "(ARRAY[1, 2, 3, 4, 5, 6])[2:5:3]",
                new Subscript.Slice(
                    LowerBound: Expr.MakeValue(TestUtils.Number("2")),
                    UpperBound: Expr.MakeValue(TestUtils.Number("5")),
                    Stride: Expr.MakeValue(TestUtils.Number("3")))
            ),
            (
                "arr[array_length(arr) - 3:array_length(arr) - 1]",
                new Subscript.Slice(
                    LowerBound: new Expr.BinaryOp(
                        Left: TestUtils.Call("array_length", new Expr[] { new Expr.Identifier(new Ident("arr")) }),
                        Op: new BinaryOperator.Minus(),
                        Right: Expr.MakeValue(TestUtils.Number("3"))),
                    UpperBound: new Expr.BinaryOp(
                        Left: TestUtils.Call("array_length", new Expr[] { new Expr.Identifier(new Ident("arr")) }),
                        Op: new BinaryOperator.Minus(),
                        Right: Expr.MakeValue(TestUtils.Number("1"))),
                    Stride: null)
            ),
            (
                "(ARRAY[1, 2, 3, 4, 5, 6])[:5]",
                new Subscript.Slice(
                    LowerBound: null,
                    UpperBound: Expr.MakeValue(TestUtils.Number("5")),
                    Stride: null)
            ),
            (
                "(ARRAY[1, 2, 3, 4, 5, 6])[2:]",
                new Subscript.Slice(
                    LowerBound: Expr.MakeValue(TestUtils.Number("2")),
                    UpperBound: null,
                    Stride: null)
            ),
            (
                "(ARRAY[1, 2, 3, 4, 5, 6])[:]",
                new Subscript.Slice(
                    LowerBound: null,
                    UpperBound: null,
                    Stride: null)
            ),
        };
        foreach (var (sql, expect) in tests)
        {
            if (PgAndGeneric().VerifiedExpr(sql) is not Expr.CompoundFieldAccess { AccessChain: var accessChain })
            {
                Assert.Fail("expected subscript expr");
                return;
            }
            if (accessChain.Last is not AccessExpr.Subscript { Value: var subscript })
            {
                Assert.Fail("expected subscript");
                return;
            }
            Assert.Equal(expect, subscript);
        }

        PgAndGeneric().VerifiedExpr("schedule[:2][2:]");
    }

