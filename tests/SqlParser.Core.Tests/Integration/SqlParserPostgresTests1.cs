    /// </summary>
    /// <remarks>
    /// <para><b>Implementative details</b></para>
    /// <para>
    /// At this time, since the parser library is not intended to take care of the semantics of the SQL statements,
    /// there is no way to verify the correctness of the operator classes, nor whether they are valid for the given
    /// index type. This test is only intended to verify that the parser can correctly parse the statement. For this
    /// reason, the test includes a <c>totally_not_valid</c> operator class.
    /// </para>
    /// </remarks>
    [Fact]
    public void parse_create_indices_with_operator_classes()
    {
        var indices = new IndexType[]
        {
            new IndexType.GIN(),
            new IndexType.GiST(),
            new IndexType.SPGiST(),
            new IndexType.Custom(new Ident("CustomIndexType")),
        };
        var operatorClasses = new ObjectName?[]
        {
            null,
            new ObjectName(Sequence.Of<ObjectNamePart>(new ObjectNamePart.Identifier(new Ident(
                "gin_trgm_ops")))),
