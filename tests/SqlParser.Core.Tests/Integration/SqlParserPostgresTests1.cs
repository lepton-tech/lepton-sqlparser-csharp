            "~**", // Overlap Coefficient
            "~~~", // Q-Gram Distance
            "~=~", // Smith-Waterman Coefficient
            "~!~", // Smith-Waterman-Gotoh Coefficient
            "~*~", // Soundex Distance
            // soundex_operator
            ">@@<", // Soundex matches
