    [Fact]
    public void parse_create_sequence()
    {
        // SimpleLogger::new().init().unwrap();

        var sql1 = "CREATE SEQUENCE  name0";
        Pg().OneStatementParsesTo(sql1, "CREATE SEQUENCE name0");

        var sql2 = "CREATE SEQUENCE  IF NOT EXISTS  name0";
        Pg().OneStatementParsesTo(sql2, "CREATE SEQUENCE IF NOT EXISTS name0");

        var sql3 = "CREATE TEMPORARY SEQUENCE  IF NOT EXISTS  name0";
        Pg().OneStatementParsesTo(sql3, "CREATE TEMPORARY SEQUENCE IF NOT EXISTS name0");

        var sql4 = "CREATE TEMPORARY SEQUENCE  name0";
        Pg().OneStatementParsesTo(sql4, "CREATE TEMPORARY SEQUENCE name0");

        sql2 = "CREATE TEMPORARY SEQUENCE IF NOT EXISTS  name1\n" +
            "      AS BIGINT\n" +
            "     INCREMENT BY  1\n" +
            "     MINVALUE 1  MAXVALUE 20\n" +
            "     START WITH 10";
        Pg().OneStatementParsesTo(
            sql2,
            "CREATE TEMPORARY SEQUENCE IF NOT EXISTS name1 AS BIGINT INCREMENT BY 1 MINVALUE 1 MAXVALUE 20 START WITH 10");

        sql3 = "CREATE SEQUENCE IF NOT EXISTS  name2\n" +
            "     AS BIGINT\n" +
            "     INCREMENT  1\n" +
            "     MINVALUE 1  MAXVALUE 20\n" +
            "     START WITH 10 CACHE 2 NO CYCLE";
        Pg().OneStatementParsesTo(
            sql3,
            "CREATE SEQUENCE IF NOT EXISTS name2 AS BIGINT INCREMENT 1 MINVALUE 1 MAXVALUE 20 START WITH 10 CACHE 2 NO CYCLE");

        sql4 = "CREATE TEMPORARY SEQUENCE  IF NOT EXISTS  name3\n" +
            "         INCREMENT  1\n" +
            "     NO MINVALUE  MAXVALUE 20 CACHE 2 CYCLE";
        Pg().OneStatementParsesTo(
            sql4,
            "CREATE TEMPORARY SEQUENCE IF NOT EXISTS name3 INCREMENT 1 NO MINVALUE MAXVALUE 20 CACHE 2 CYCLE");

        var sql5 = "CREATE TEMPORARY SEQUENCE  IF NOT EXISTS  name3\n" +
            "         INCREMENT  1\n" +
            "     NO MINVALUE  MAXVALUE 20 OWNED BY public.table01";
        Pg().OneStatementParsesTo(
            sql5,
            "CREATE TEMPORARY SEQUENCE IF NOT EXISTS name3 INCREMENT 1 NO MINVALUE MAXVALUE 20 OWNED BY public.table01");

        var sql6 = "CREATE TEMPORARY SEQUENCE  IF NOT EXISTS  name3\n" +
            "         INCREMENT  1\n" +
            "     NO MINVALUE  MAXVALUE 20 OWNED BY NONE";
        Pg().OneStatementParsesTo(
            sql6,
            "CREATE TEMPORARY SEQUENCE IF NOT EXISTS name3 INCREMENT 1 NO MINVALUE MAXVALUE 20 OWNED BY NONE");

        var sql7 = "CREATE SEQUENCE name4\n" +
            "    AS BIGINT\n" +
            "    INCREMENT   -15\n" +
            "    MINVALUE - 2000  MAXVALUE -50\n" +
            "    START WITH -   60";
        Pg().OneStatementParsesTo(
            sql7,
            "CREATE SEQUENCE name4 AS BIGINT INCREMENT -15 MINVALUE -2000 MAXVALUE -50 START WITH -60");

        var sql8 = "CREATE SEQUENCE name5\n" +
            "    AS BIGINT\n" +
            "    INCREMENT   +10\n" +
            "    MINVALUE + 30  MAXVALUE +5000\n" +
            "    START WITH +   45";
        Pg().OneStatementParsesTo(
            sql8,
            "CREATE SEQUENCE name5 AS BIGINT INCREMENT +10 MINVALUE +30 MAXVALUE +5000 START WITH +45");

        // assert!(matches!(.., Err(ParserError::ParserError(_))))
        var ex = Assert.Throws<ParserException>(
            () => Pg().ParseSqlStatements("CREATE SEQUENCE foo INCREMENT 1 NO MINVALUE NO"));
        Assert.IsType<ParserError.ParserErrorValue>(ex.Error);
    }

