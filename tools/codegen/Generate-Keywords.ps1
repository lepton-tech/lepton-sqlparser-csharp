<#
.SYNOPSIS
    Gera src/Lepton.SqlParser.Core/Keywords.g.cs a partir de upstream/sqlparser-rs/src/keywords.rs.

.DESCRIPTION
    O keywords.rs do Rust é declarativo (macro define_keywords! + listas RESERVED_*), então é
    gerado em vez de portado à mão: assim uma keyword nova no upstream nunca é "esquecida".
    Rode sempre que o upstream for atualizado (ver skill sync-upstream).

.EXAMPLE
    pwsh tools/codegen/Generate-Keywords.ps1
#>
[CmdletBinding()]
param(
    [string]$Source = (Join-Path $PSScriptRoot '..\..\upstream\sqlparser-rs\src\keywords.rs'),
    [string]$Output = (Join-Path $PSScriptRoot '..\..\src\Lepton.SqlParser.Core\Keywords.g.cs')
)

$ErrorActionPreference = 'Stop'
$lines = Get-Content $Source
$config = Get-Content (Join-Path $PSScriptRoot '..\..\UPSTREAM.json') -Raw | ConvertFrom-Json
$version = $config.'sqlparser-rs'.baselineTag

# --- define_keywords!( ... ); ------------------------------------------------------------
$start = ($lines | Select-String -Pattern '^define_keywords!\($' | Select-Object -First 1).LineNumber
if (-not $start) { throw 'define_keywords!( não encontrado' }
$keywords = New-Object System.Collections.Generic.List[object]
for ($i = $start; $i -lt $lines.Count; $i++) {
    $line = $lines[$i].Trim()
    if ($line -eq ');') { break }
    if ($line -eq '' -or $line.StartsWith('//')) { continue }
    $m = [regex]::Match($line, '^(?<id>[A-Za-z_][A-Za-z0-9_]*)(\s*=\s*"(?<str>[^"]*)")?\s*,?$')
    if (-not $m.Success) { throw "Linha de keyword não reconhecida ($($i + 1)): $line" }
    $id = $m.Groups['id'].Value
    $str = if ($m.Groups['str'].Success) { $m.Groups['str'].Value } else { $id }
    $keywords.Add([pscustomobject]@{ Id = $id; Text = $str })
}

# O tokenizer faz busca binária ordinal (igual ao binary_search do Rust): a ordem precisa ser estrita.
for ($i = 1; $i -lt $keywords.Count; $i++) {
    if ([string]::CompareOrdinal($keywords[$i - 1].Text, $keywords[$i].Text) -ge 0) {
        throw "Keywords fora de ordem: '$($keywords[$i - 1].Text)' antes de '$($keywords[$i].Text)'"
    }
}

# --- pub const RESERVED_*: &[Keyword] = &[ ... ]; -----------------------------------------
function Get-KeywordList([string]$name) {
    $begin = ($lines | Select-String -Pattern "^pub const $name\s*:\s*&\[Keyword\]\s*=\s*&\[" | Select-Object -First 1).LineNumber
    if (-not $begin) { throw "Lista $name não encontrada" }
    $items = New-Object System.Collections.Generic.List[string]
    for ($i = $begin; $i -lt $lines.Count; $i++) {
        $line = $lines[$i].Trim()
        if ($line -eq '];') { break }
        foreach ($m in [regex]::Matches($line, 'Keyword::([A-Za-z_][A-Za-z0-9_]*)')) {
            $items.Add($m.Groups[1].Value)
        }
    }
    return , $items
}

function ConvertTo-PascalCase([string]$screaming) {
    ($screaming.ToLowerInvariant().Split('_') | ForEach-Object { if ($_) { $_.Substring(0, 1).ToUpperInvariant() + $_.Substring(1) } }) -join ''
}

$lists = 'RESERVED_FOR_TABLE_ALIAS', 'RESERVED_FOR_COLUMN_ALIAS', 'RESERVED_FOR_TABLE_FACTOR', 'RESERVED_FOR_IDENTIFIER'

# --- Emissão -------------------------------------------------------------------------------
$sb = New-Object System.Text.StringBuilder
$header = Get-Content (Join-Path $PSScriptRoot '..\..\upstream\sqlparser-rs\HEADER')
foreach ($h in $header) { [void]$sb.AppendLine($h) }
[void]$sb.AppendLine('//')
[void]$sb.AppendLine("// Portado para C# a partir de sqlparser-rs $version, src/keywords.rs.")
[void]$sb.AppendLine('// Modificado: tradução de Rust para C#.')
[void]$sb.AppendLine('//')
[void]$sb.AppendLine('// <auto-generated>')
[void]$sb.AppendLine('// Gerado por tools/codegen/Generate-Keywords.ps1. NÃO EDITE À MÃO: rode o script novamente.')
[void]$sb.AppendLine('// </auto-generated>')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('#nullable enable')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('namespace Lepton.SqlParser.Core;')
[void]$sb.AppendLine('')
# Doc comments (///) só com o texto do Rust; notas do port em // (convencoes.md §12).
[void]$sb.AppendLine('/// <summary>An enumeration of SQL keywords recognized by the parser.</summary>')
[void]$sb.AppendLine('// Rust: `keywords::Keyword`.')
[void]$sb.AppendLine('public enum Keyword')
[void]$sb.AppendLine('{')
[void]$sb.AppendLine('    /// <summary>Represents no keyword.</summary>')
[void]$sb.AppendLine('    NoKeyword,')
foreach ($k in $keywords) {
    [void]$sb.AppendLine("    /// <summary>The <c>$($k.Text)</c> SQL keyword.</summary>")
    [void]$sb.AppendLine("    $($k.Id),")
}
[void]$sb.AppendLine('}')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('// Constantes e listas do módulo `keywords` do Rust.')
[void]$sb.AppendLine('public static partial class Keywords')
[void]$sb.AppendLine('{')
[void]$sb.AppendLine('    /// <summary>Array of all SQL keywords as string constants.</summary>')
[void]$sb.AppendLine('    // Rust: `ALL_KEYWORDS`. Em ordem ordinal, como exige a busca binária de Lookup.')
[void]$sb.AppendLine('    internal static readonly string[] AllKeywordsArray =')
[void]$sb.AppendLine('    {')
foreach ($k in $keywords) { [void]$sb.AppendLine("        `"$($k.Text)`",") }
[void]$sb.AppendLine('    };')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('    /// <summary>Array of all <c>Keyword</c> enum values in declaration order.</summary>')
[void]$sb.AppendLine('    // Rust: `ALL_KEYWORDS_INDEX`.')
[void]$sb.AppendLine('    internal static readonly Keyword[] AllKeywordsIndexArray =')
[void]$sb.AppendLine('    {')
foreach ($k in $keywords) { [void]$sb.AppendLine("        Keyword.$($k.Id),") }
[void]$sb.AppendLine('    };')
foreach ($name in $lists) {
    $items = Get-KeywordList $name
    $pascal = ConvertTo-PascalCase $name
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine("    // Rust: ``$name``.")
    [void]$sb.AppendLine("    internal static readonly Keyword[] ${pascal}Array =")
    [void]$sb.AppendLine('    {')
    foreach ($it in $items) { [void]$sb.AppendLine("        Keyword.$it,") }
    [void]$sb.AppendLine('    };')
}
[void]$sb.AppendLine('')
[void]$sb.AppendLine('    // Texto SQL de cada keyword, indexado por `(int)Keyword` (Rust: `impl Display for Keyword`).')
[void]$sb.AppendLine('    internal static readonly string[] KeywordTexts =')
[void]$sb.AppendLine('    {')
[void]$sb.AppendLine('        "NoKeyword",')
foreach ($k in $keywords) { [void]$sb.AppendLine("        `"$($k.Text)`",") }
[void]$sb.AppendLine('    };')
[void]$sb.AppendLine('}')

$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText((Resolve-Path (Split-Path $Output -Parent)).Path + '\' + (Split-Path $Output -Leaf), $sb.ToString().Replace("`r`n", "`n").Replace("`n", "`r`n"), $utf8NoBom)
Write-Host "Gerado $Output com $($keywords.Count) keywords."
