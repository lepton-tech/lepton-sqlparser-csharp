// Código próprio do port (ferramenta de desenvolvimento). Gera o equivalente do derive Visit/VisitMut
// de sqlparser-rs para cada tipo da AST C#. Ver docs/adr/0007-visitor.md.
//
// Uso (normalmente via tools/codegen/Generate-Visitor.ps1):
//   VisitorGen --assembly <SqlParser.Core.dll sem código gerado> --sources <src/SqlParser.Core>
//              --rust <upstream/sqlparser-rs> --output <src/SqlParser.Core/Ast/Visitor/Generated>
//              --version <v0.63.0> --header <upstream/sqlparser-rs/HEADER> [--check]

using System.Reflection;
using System.Runtime.Loader;
using System.Text;
using VisitorGen;

var options = new Dictionary<string, string>(StringComparer.Ordinal);
var check = false;
for (var i = 0; i < args.Length; i++)
{
    if (args[i] == "--check")
    {
        check = true;
        continue;
    }
    if (!args[i].StartsWith("--", StringComparison.Ordinal) || i + 1 >= args.Length)
    {
        Console.Error.WriteLine($"Argumento inválido: {args[i]}");
        return 2;
    }
    options[args[i].Substring(2)] = args[++i];
}
string Opt(string name) => options.TryGetValue(name, out var v) ? v : throw new ArgumentException($"Falta --{name}");

var assemblyPath = Path.GetFullPath(Opt("assembly"));
var context = new AssemblyLoadContext("VisitorGen", isCollectible: false);
var assembly = context.LoadFromAssemblyPath(assemblyPath);
var (rustItems, rustManual) = RustModel.Load(Opt("rust"));
var model = new CsModel(assembly, Opt("sources"));
var analysis = new Analysis(model, rustItems, rustManual);

foreach (var w in analysis.Warnings)
{
    Console.WriteLine("AVISO: " + w);
}
if (analysis.Errors.Count > 0)
{
    foreach (var e in analysis.Errors)
    {
        Console.Error.WriteLine("ERRO: " + e);
    }
    Console.Error.WriteLine($"{analysis.Errors.Count} erro(s): nada foi gerado.");
    return 1;
}

var version = Opt("version");
var asfHeader = File.ReadAllLines(Opt("header"));
var outputDir = Path.GetFullPath(Opt("output"));

// Um arquivo por pasta de origem (Ast/Mod → Ast.Mod.g.cs), tipos na ordem dos fontes e dos metadados.
var groups = analysis.Visitable
    .Where(t => !analysis.Manual.Contains(t))
    .Select(t => (Type: t, Source: analysis.PrimarySource(t)))
    .GroupBy(x => Path.GetDirectoryName(x.Source)!.Replace('\\', '/'))
    .OrderBy(g => g.Key, StringComparer.Ordinal);

var files = new Dictionary<string, string>(StringComparer.Ordinal);
foreach (var group in groups)
{
    var sb = new StringBuilder();
    foreach (var h in asfHeader)
    {
        sb.Append(h).Append('\n');
    }
    sb.Append("//\n");
    sb.Append($"// Portado para C# a partir de sqlparser-rs {version}: código que o derive Visit/VisitMut\n");
    sb.Append("// (derive/src/visit.rs) gera para os tipos declarados em src/SqlParser.Core/" + group.Key + ".\n");
    sb.Append("// Modificado: tradução de Rust para C#.\n");
    sb.Append("//\n");
    sb.Append("// <auto-generated>\n");
    sb.Append("// Gerado por tools/codegen/Generate-Visitor.ps1. NÃO EDITE À MÃO: rode o script novamente.\n");
    sb.Append("// </auto-generated>\n");
    sb.Append('\n');
    sb.Append("#nullable enable\n");
    var byNamespace = group
        .OrderBy(x => x.Source, StringComparer.Ordinal)
        .ThenBy(x => x.Type.MetadataToken)
        .GroupBy(x => x.Type.Namespace!);
    foreach (var ns in byNamespace)
    {
        sb.Append('\n');
        sb.Append($"namespace {ns.Key}\n{{\n");
        var first = true;
        foreach (var (type, source) in ns)
        {
            if (!first)
            {
                sb.Append('\n');
            }
            first = false;
            var item = analysis.RustOf[type];
            var header = $"Rust: {item.File}, {item.Kind} {item.Name}"
                + (item.TypeHook is { } th ? $", visit(with = \"{th}\")" : "")
                + $". C#: {source}.";
            var emitter = new Emitter(analysis);
            emitter.EmitType(type, header);
            foreach (var line in emitter.ToString().Split('\n'))
            {
                sb.Append(line.Length == 0 ? "" : "    " + line).Append('\n');
            }
            // remove a linha vazia extra do Split
            sb.Length -= 1;
        }
        sb.Append("}\n");
    }
    var fileName = group.Key.Replace('/', '.') + ".g.cs";
    files[fileName] = sb.ToString();
}

if (check)
{
    var stale = new List<string>();
    foreach (var (name, content) in files)
    {
        var path = Path.Combine(outputDir, name);
        if (!File.Exists(path) || File.ReadAllText(path).Replace("\r\n", "\n") != content)
        {
            stale.Add(name);
        }
    }
    foreach (var existing in Directory.Exists(outputDir) ? Directory.GetFiles(outputDir, "*.g.cs") : Array.Empty<string>())
    {
        if (!files.ContainsKey(Path.GetFileName(existing)))
        {
            stale.Add(Path.GetFileName(existing) + " (sobrando)");
        }
    }
    if (stale.Count > 0)
    {
        Console.Error.WriteLine("Código gerado desatualizado: " + string.Join(", ", stale));
        return 1;
    }
    Console.WriteLine("Código gerado do visitor está atualizado.");
    return 0;
}

Directory.CreateDirectory(outputDir);
foreach (var existing in Directory.GetFiles(outputDir, "*.g.cs"))
{
    if (!files.ContainsKey(Path.GetFileName(existing)))
    {
        File.Delete(existing);
    }
}
foreach (var (name, content) in files)
{
    File.WriteAllText(Path.Combine(outputDir, name), content, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
}

Console.WriteLine($"Tipos Rust com derive(Visit): {rustItems.Count}; impl manual: {string.Join(", ", rustManual)}.");
Console.WriteLine($"Tipos C# visitáveis: {analysis.Visitable.Count} (+ {analysis.LeafEnums.Count} enums C# folha); nós: {analysis.NodeCount}, alcançam ganchos: {analysis.ReachCount}.");
Console.WriteLine($"Gerados {files.Count} arquivo(s) em {outputDir}.");
return 0;
